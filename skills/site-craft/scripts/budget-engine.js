#!/usr/bin/env node
// Internal engine for budget-check.sh. Not meant to be run by hand.
//
// Three checks against one URL:
//  1. JS weight: every script response the page fetches (including ones
//     injected after load), plus the text of every inline `<script>` tag
//     (which never shows up as a network response), transfer size and a
//     gzip size we recompute ourselves so the number is comparable
//     regardless of what encoding the server actually used, split into
//     first-party vs third-party and summed, compared to a byte budget.
//  2. JS-off: loads the page with JavaScript disabled and compares the
//     visible text length (document.body.innerText) to a JS-on load.
//  3. Reduced motion: two independent measures.
//     a. Web Animations API animations (document.getAnimations()) that are
//        running or pending, after load and after one scroll, with and
//        without reduced motion emulated. Engine-specific: only sees CSS
//        animations/transitions and explicit element.animate() calls.
//     b. Engine-agnostic visible-motion check: two screenshots a fixed gap
//        apart, with scrolling stopped, compared byte-for-byte, after load
//        and after one scroll. Sees anything that changes pixels on
//        screen, regardless of what drives it (CSS, WAAPI, rAF, a JS
//        animation library, canvas, SVG SMIL). Does not say *what*
//        animated or isolate a specific element, only whether anything in
//        the viewport visibly changed between the two shots.
//
// Usage: node budget-engine.js <url> <budgetGzipBytes> <settleAfterLoadMs>
// Env: SITECRAFT_CHROMIUM_RESOLVED (optional)
// Prints one "RESULT <json>" line with everything measured.

const zlib = require('zlib');
const { chromium } = require('playwright');

const url = process.argv[2];
const budgetBytes = parseInt(process.argv[3], 10);
const SETTLE_AFTER_LOAD_MS = parseInt(process.argv[4], 10);
const chromiumPath = process.env.SITECRAFT_CHROMIUM_RESOLVED || undefined;

if (!url || !Number.isFinite(budgetBytes) || !Number.isFinite(SETTLE_AFTER_LOAD_MS)) {
  console.error('usage: node budget-engine.js <url> <budgetGzipBytes> <settleAfterLoadMs>');
  process.exit(2);
}

// How long to wait after the `load` event (and after networkidle, or 5s,
// whichever comes first) before closing out the JS-weight script list. This
// is what catches idle-callback-deferred vendor bundles and lazy chunks
// injected after the page looks "done". Configurable because the right
// window depends on the site; see README.md for the flag/env var.
console.error(`site-craft: settle-after-load window = ${SETTLE_AFTER_LOAD_MS}ms`);

const SETTLE_AFTER_SCROLL_MS = 600;

// Gap between the two screenshots compared at each visible-motion
// checkpoint (see measureVisualMotion below).
const VISUAL_DIFF_GAP_MS = 500;

let pageHost = null;
try {
  pageHost = new URL(url).hostname;
} catch (e) {
  // leave pageHost null; classifyParty falls back to "third" for everything
}

// First-party = same hostname as the page URL (not eTLD+1, so
// `cdn.example.com` counts as third-party against `example.com` even
// though it is the same company -- a narrower, more conservative
// definition that is simple to state and does not require a public-suffix
// list). data: and blob: scripts have no hostname and are treated as
// first-party, since they are embedded in or generated by the page itself
// rather than fetched from a separate origin.
function classifyParty(scriptUrl) {
  if (/^data:/i.test(scriptUrl) || /^blob:/i.test(scriptUrl)) return 'first';
  try {
    const h = new URL(scriptUrl).hostname;
    if (!pageHost) return 'third';
    return h === pageHost ? 'first' : 'third';
  } catch (e) {
    return 'third';
  }
}

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

function sumBy(list, pred, field) {
  return list.filter(pred).reduce((sum, s) => sum + (s[field] || 0), 0);
}

// CDP's Network domain only ever fires for a fetched resource. A <script>
// with no src makes no network request, so inline JS would measure 0 B
// without this. Read every inline JS script's text content after load, from
// the live DOM, and gzip it the same way a fetched body is gzipped above, so
// the two numbers are comparable and summed into one total. Data blocks
// (ld+json, importmap, speculationrules) are not JS and are skipped.
async function measureInlineScripts(page) {
  const texts = await page.$$eval('script:not([src])', (nodes) => {
    const JS_TYPES = ['', 'text/javascript', 'application/javascript', 'module'];
    return nodes.map((n) => {
      const type = (n.getAttribute('type') || '').trim().toLowerCase();
      return JS_TYPES.includes(type) ? (n.textContent || '') : '';
    });
  });
  return texts
    .map((text, i) => {
      if (!text.trim()) return null;
      const buf = Buffer.from(text, 'utf8');
      return {
        url: `inline:script[${i}]`,
        party: 'first', // embedded in the page's own HTML, not a separate origin
        status: null,
        decodedBytes: buf.length,
        gzipBytes: zlib.gzipSync(buf, { level: 9 }).length,
        transferBytes: buf.length,
        transferApprox: true,
        bodyError: null,
        inline: true,
      };
    })
    .filter(Boolean);
}

async function measureJsWeight(browser) {
  const context = await browser.newContext();
  const page = await context.newPage();
  const cdp = await context.newCDPSession(page);
  await cdp.send('Network.enable');

  const requests = new Map(); // requestId -> {url, type}
  const finished = new Map(); // requestId -> encodedDataLength

  cdp.on('Network.requestWillBeSent', (e) => {
    requests.set(e.requestId, { url: e.request.url, type: e.type });
  });
  cdp.on('Network.responseReceived', (e) => {
    const r = requests.get(e.requestId);
    if (r) {
      r.mimeType = e.response.mimeType;
      r.status = e.response.status;
      r.headers = e.response.headers;
    }
  });
  cdp.on('Network.loadingFinished', (e) => {
    finished.set(e.requestId, e.encodedDataLength);
  });

  let navError = null;
  try {
    await page.goto(url, { waitUntil: 'load', timeout: 30000 });
  } catch (e) {
    navError = e.message;
  }
  try {
    await page.waitForLoadState('networkidle', { timeout: 5000 });
  } catch (e) {
    // fall through to the fixed settle delay below
  }
  await sleep(SETTLE_AFTER_LOAD_MS);

  const scripts = [];
  for (const [requestId, info] of requests.entries()) {
    const isScript =
      info.type === 'Script' ||
      (info.mimeType && /javascript|ecmascript/i.test(info.mimeType));
    if (!isScript) continue;

    let decodedBytes = null;
    let gzipBytes = null;
    let bodyError = null;
    try {
      const body = await cdp.send('Network.getResponseBody', { requestId });
      const buf = body.base64Encoded
        ? Buffer.from(body.body, 'base64')
        : Buffer.from(body.body, 'utf8');
      decodedBytes = buf.length;
      gzipBytes = zlib.gzipSync(buf, { level: 9 }).length;
    } catch (e) {
      bodyError = e.message;
    }

    const contentLengthHeader = info.headers && (info.headers['content-length'] || info.headers['Content-Length']);
    let transferBytes = finished.get(requestId);
    let transferApprox = false;
    if (transferBytes === undefined) {
      transferBytes = contentLengthHeader ? parseInt(contentLengthHeader, 10) : decodedBytes;
      transferApprox = true;
    }

    scripts.push({
      url: info.url,
      party: classifyParty(info.url),
      status: info.status,
      decodedBytes,
      gzipBytes,
      transferBytes,
      transferApprox,
      bodyError,
    });
  }

  const inlineScripts = await measureInlineScripts(page);
  scripts.push(...inlineScripts);

  await context.close();

  const isFirst = (s) => s.party === 'first';
  const isThird = (s) => s.party === 'third';

  const totalGzip = sumBy(scripts, () => true, 'gzipBytes');
  const totalGzipFirst = sumBy(scripts, isFirst, 'gzipBytes');
  const totalGzipThird = sumBy(scripts, isThird, 'gzipBytes');
  const totalTransfer = sumBy(scripts, () => true, 'transferBytes');
  const totalTransferFirst = sumBy(scripts, isFirst, 'transferBytes');
  const totalTransferThird = sumBy(scripts, isThird, 'transferBytes');
  const unmeasured = scripts.filter((s) => s.bodyError).length;
  const unmeasuredFirst = scripts.filter((s) => s.bodyError && isFirst(s)).length;
  const unmeasuredThird = scripts.filter((s) => s.bodyError && isThird(s)).length;

  return {
    navError,
    pageHost,
    scripts,
    totalGzip,
    totalGzipFirst,
    totalGzipThird,
    totalTransfer,
    totalTransferFirst,
    totalTransferThird,
    unmeasured,
    unmeasuredFirst,
    unmeasuredThird,
  };
}

async function measureVisibleTextLength(browser, javaScriptEnabled) {
  const context = await browser.newContext({ javaScriptEnabled });
  const page = await context.newPage();
  let navError = null;
  try {
    await page.goto(url, { waitUntil: 'load', timeout: 30000 });
  } catch (e) {
    navError = e.message;
  }
  try {
    await page.waitForLoadState('networkidle', { timeout: 5000 });
  } catch (e) {
    // ignore
  }
  await sleep(1500);

  let length = 0;
  if (!navError) {
    try {
      // innerText is a JS call; with JS disabled we still can run page.evaluate
      // (Playwright's own instrumentation, not page script), so this measures
      // what a screen reader / search engine sees in the raw, un-scripted DOM.
      length = await page.evaluate(() => (document.body ? document.body.innerText.length : 0));
    } catch (e) {
      navError = e.message;
    }
  }

  await context.close();
  return { navError, length };
}

async function countAnimations(browser, reducedMotion) {
  const context = await browser.newContext({
    reducedMotion: reducedMotion ? 'reduce' : 'no-preference',
  });
  const page = await context.newPage();
  let navError = null;
  try {
    await page.goto(url, { waitUntil: 'load', timeout: 30000 });
  } catch (e) {
    navError = e.message;
  }
  try {
    await page.waitForLoadState('networkidle', { timeout: 5000 });
  } catch (e) {
    // ignore
  }
  await sleep(1500);

  const countActive = () =>
    page.evaluate(
      () => document.getAnimations().filter((a) => a.playState === 'running' || a.playState === 'pending').length
    );

  let afterLoad = 0;
  let afterScroll = 0;
  if (!navError) {
    try {
      afterLoad = await countActive();
      const viewportHeight = page.viewportSize().height;
      await page.evaluate((h) => window.scrollTo(0, h), viewportHeight);
      await sleep(SETTLE_AFTER_SCROLL_MS);
      afterScroll = await countActive();
    } catch (e) {
      navError = e.message;
    }
  }

  await context.close();
  return { navError, afterLoad, afterScroll };
}

// Engine-agnostic companion to countAnimations: instead of asking the
// browser which animation objects exist, it just looks at the pixels.
// Two screenshots VISUAL_DIFF_GAP_MS apart, with scrolling stopped, are
// compared byte-for-byte (Playwright's PNG screenshots of an unchanged
// page are deterministic, so an identical page state produces identical
// bytes). Any difference means something visibly changed in that window --
// a CSS animation, a requestAnimationFrame loop, a JS animation library, a
// canvas redraw, an SVG SMIL animation, all look the same from here: pixels
// moved. What it cannot do: say *what* moved, isolate a single element, or
// catch motion that happens to land on the exact same pixels twice by
// coincidence (not realistic for genuine animation, but means this is a
// "did anything move" signal, not a frame-accurate diff map).
//
// Two things are deliberately excluded so they cannot produce a false
// FAIL: a playing <video> element (its own frames change constantly,
// independent of prefers-reduced-motion -- the media query does not pause
// video -- and that is a separate, already-documented concern, not
// decorative motion) is hidden with a stylesheet before either screenshot;
// and a blinking text caret is never triggered in the first place because
// this check never focuses an editable element.
async function measureVisualMotion(browser, reducedMotion) {
  const context = await browser.newContext({
    viewport: { width: 1280, height: 800 },
    reducedMotion: reducedMotion ? 'reduce' : 'no-preference',
  });
  const page = await context.newPage();
  let navError = null;
  try {
    await page.goto(url, { waitUntil: 'load', timeout: 30000 });
  } catch (e) {
    navError = e.message;
  }
  try {
    await page.waitForLoadState('networkidle', { timeout: 5000 });
  } catch (e) {
    // ignore
  }
  await sleep(1500);

  if (!navError) {
    try {
      await page.addStyleTag({ content: 'video { visibility: hidden !important; }' });
    } catch (e) {
      navError = e.message;
    }
  }

  async function diffCheckpoint() {
    const shotA = await page.screenshot({ type: 'png' });
    await sleep(VISUAL_DIFF_GAP_MS);
    const shotB = await page.screenshot({ type: 'png' });
    return !shotA.equals(shotB);
  }

  let afterLoadMoved = null;
  let afterScrollMoved = null;
  if (!navError) {
    try {
      afterLoadMoved = await diffCheckpoint();
      const viewportHeight = page.viewportSize().height;
      await page.evaluate((h) => window.scrollTo(0, h), viewportHeight);
      // Let a scroll-triggered reveal start, then stop scrolling -- the
      // diff itself only runs while the page is not being scrolled.
      await sleep(SETTLE_AFTER_SCROLL_MS);
      afterScrollMoved = await diffCheckpoint();
    } catch (e) {
      navError = e.message;
    }
  }

  await context.close();
  return { navError, afterLoadMoved, afterScrollMoved, diffGapMs: VISUAL_DIFF_GAP_MS };
}

(async () => {
  const launchOpts = { headless: true };
  if (chromiumPath) launchOpts.executablePath = chromiumPath;

  let browser;
  try {
    browser = await chromium.launch(launchOpts);
  } catch (e) {
    console.error(`site-craft: chromium launch failed: ${e.message}`);
    process.exit(1);
  }

  try {
    const jsWeight = await measureJsWeight(browser);
    const jsOn = await measureVisibleTextLength(browser, true);
    const jsOff = await measureVisibleTextLength(browser, false);
    const reduced = await countAnimations(browser, true);
    const normal = await countAnimations(browser, false);
    const visualReduced = await measureVisualMotion(browser, true);
    const visualNormal = await measureVisualMotion(browser, false);

    await browser.close();

    const textRatio = jsOn.length > 0 ? jsOff.length / jsOn.length : null;

    const result = {
      url,
      budgetBytes,
      settleAfterLoadMs: SETTLE_AFTER_LOAD_MS,
      jsWeight,
      textLengths: {
        jsOnChars: jsOn.length,
        jsOffChars: jsOff.length,
        ratio: textRatio,
        jsOnNavError: jsOn.navError,
        jsOffNavError: jsOff.navError,
      },
      animations: { reduced, normal },
      visualMotion: { reduced: visualReduced, normal: visualNormal },
    };
    console.log('RESULT ' + JSON.stringify(result));
  } catch (e) {
    console.error(`site-craft: budget-check failed: ${e.message}`);
    await browser.close().catch(() => {});
    process.exit(1);
  }
})();
